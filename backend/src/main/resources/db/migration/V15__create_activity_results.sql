CREATE TABLE activity_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scheduled_visit_id BIGINT NOT NULL REFERENCES scheduled_visits (id) ON DELETE CASCADE,
    planned_activity_id BIGINT NOT NULL REFERENCES planned_activities (id),
    value VARCHAR(200) NOT NULL,
    note VARCHAR(500),
    recorded_by_user_id BIGINT NOT NULL REFERENCES users (id),
    recorded_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_activity_results_visit_activity UNIQUE (scheduled_visit_id, planned_activity_id),
    CONSTRAINT ck_activity_results_value CHECK (btrim(value) <> '')
);
