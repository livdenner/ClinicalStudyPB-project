ALTER TABLE candidates ADD CONSTRAINT uq_candidates_id_study UNIQUE (id, study_id);

CREATE TABLE participants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    study_id BIGINT NOT NULL REFERENCES studies (id) ON DELETE CASCADE,
    candidate_id BIGINT NOT NULL UNIQUE,
    included_by BIGINT NOT NULL REFERENCES users (id),
    included_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_participants_candidate_study FOREIGN KEY (candidate_id, study_id)
        REFERENCES candidates (id, study_id) ON DELETE CASCADE
);

CREATE INDEX ix_participants_study ON participants (study_id);
