CREATE TABLE eligibility_answers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id BIGINT NOT NULL REFERENCES candidates (id) ON DELETE CASCADE,
    criterion_id BIGINT NOT NULL REFERENCES study_criteria (id) ON DELETE CASCADE,
    matches BOOLEAN NOT NULL,
    CONSTRAINT uq_eligibility_answer_candidate_criterion UNIQUE (candidate_id, criterion_id)
);

CREATE INDEX ix_eligibility_answers_criterion ON eligibility_answers (criterion_id);
