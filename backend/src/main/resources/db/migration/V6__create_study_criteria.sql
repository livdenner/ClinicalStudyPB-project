CREATE TABLE study_criteria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    study_id BIGINT NOT NULL REFERENCES studies (id) ON DELETE CASCADE,
    type VARCHAR(20) NOT NULL,
    description VARCHAR(500) NOT NULL,
    CONSTRAINT ck_study_criteria_type CHECK (type IN ('INCLUSION', 'EXCLUSION')),
    CONSTRAINT ck_study_criteria_description CHECK (NULLIF(TRIM(description), '') IS NOT NULL)
);

CREATE INDEX ix_study_criteria_study ON study_criteria (study_id, id);
