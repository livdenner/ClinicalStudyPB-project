ALTER TABLE participants
    ADD COLUMN status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    ADD CONSTRAINT ck_participants_status CHECK (status IN ('ACTIVE', 'WITHDRAWN'));

ALTER TABLE participants ADD CONSTRAINT uq_participants_id_study UNIQUE (id, study_id);
ALTER TABLE planned_visits ADD CONSTRAINT uq_planned_visits_id_study UNIQUE (id, study_id);

CREATE TABLE scheduled_visits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    study_id BIGINT NOT NULL REFERENCES studies (id) ON DELETE CASCADE,
    participant_id BIGINT NOT NULL,
    planned_visit_id BIGINT NOT NULL,
    scheduled_at TIMESTAMPTZ NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED',
    created_by_user_id BIGINT NOT NULL REFERENCES users (id),
    created_at TIMESTAMPTZ NOT NULL,
    outcome_by_user_id BIGINT REFERENCES users (id),
    outcome_at TIMESTAMPTZ,
    outcome_note VARCHAR(500),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_scheduled_visit_status CHECK (status IN ('SCHEDULED', 'DONE', 'ABSENT', 'CANCELLED')),
    CONSTRAINT fk_scheduled_visits_participant_study FOREIGN KEY (participant_id, study_id)
        REFERENCES participants (id, study_id) ON DELETE CASCADE,
    CONSTRAINT fk_scheduled_visits_planned_visit_study FOREIGN KEY (planned_visit_id, study_id)
        REFERENCES planned_visits (id, study_id)
);

CREATE UNIQUE INDEX ux_scheduled_visit_active
    ON scheduled_visits (participant_id, planned_visit_id)
    WHERE status IN ('SCHEDULED', 'DONE');

CREATE INDEX ix_scheduled_visits_study_scheduled
    ON scheduled_visits (study_id, scheduled_at, id);

CREATE INDEX ix_scheduled_visits_participant_scheduled
    ON scheduled_visits (participant_id, scheduled_at, id);
