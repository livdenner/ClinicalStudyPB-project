ALTER TABLE studies DROP CONSTRAINT ck_studies_status;
ALTER TABLE studies ADD CONSTRAINT ck_studies_status
    CHECK (status IN ('PLANNING', 'RECRUITMENT', 'EXECUTION', 'CLOSED', 'CANCELLED'));
ALTER TABLE studies ADD COLUMN version BIGINT NOT NULL DEFAULT 0;
ALTER TABLE studies ADD COLUMN protocol_revision BIGINT NOT NULL DEFAULT 0;

CREATE TABLE study_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    study_id BIGINT NOT NULL REFERENCES studies (id) ON DELETE CASCADE,
    actor_user_id BIGINT NOT NULL REFERENCES users (id),
    changed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    from_status VARCHAR(20) NOT NULL,
    to_status VARCHAR(20) NOT NULL,
    reason VARCHAR(1000),
    CONSTRAINT ck_history_from_status CHECK
        (from_status IN ('PLANNING', 'RECRUITMENT', 'EXECUTION', 'CLOSED', 'CANCELLED')),
    CONSTRAINT ck_history_to_status CHECK
        (to_status IN ('PLANNING', 'RECRUITMENT', 'EXECUTION', 'CLOSED', 'CANCELLED')),
    CONSTRAINT ck_history_cancel_reason CHECK
        (to_status <> 'CANCELLED' OR NULLIF(TRIM(reason), '') IS NOT NULL)
);
CREATE INDEX ix_study_status_history_study ON study_status_history (study_id, id);

CREATE TABLE planned_visits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    study_id BIGINT NOT NULL REFERENCES studies (id) ON DELETE CASCADE,
    name VARCHAR(120) NOT NULL,
    planned_date DATE NOT NULL,
    position INTEGER NOT NULL CHECK (position > 0),
    CONSTRAINT ck_planned_visit_name CHECK (NULLIF(TRIM(name), '') IS NOT NULL),
    CONSTRAINT uq_planned_visit_position UNIQUE (study_id, position) DEFERRABLE INITIALLY DEFERRED
);
CREATE INDEX ix_planned_visits_study ON planned_visits (study_id, position);

CREATE TABLE planned_activities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    planned_visit_id BIGINT NOT NULL REFERENCES planned_visits (id) ON DELETE CASCADE,
    name VARCHAR(120) NOT NULL,
    name_key VARCHAR(120) NOT NULL,
    description VARCHAR(500) NOT NULL,
    position INTEGER NOT NULL CHECK (position > 0),
    CONSTRAINT ck_planned_activity_name CHECK (NULLIF(TRIM(name), '') IS NOT NULL),
    CONSTRAINT ck_planned_activity_description CHECK (NULLIF(TRIM(description), '') IS NOT NULL),
    CONSTRAINT uq_planned_activity_position UNIQUE (planned_visit_id, position)
        DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT uq_planned_activity_name UNIQUE (planned_visit_id, name_key)
        DEFERRABLE INITIALLY DEFERRED
);
